export function placeholder(category, emoji) {
  const [a, b] = COLORS[category] || COLORS['Другое'];
  const e = emoji || EMOJI[category] || '📦';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 600 450"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="${b}"/></linearGradient></defs><rect width="600" height="450" fill="url(#g)"/><text x="300" y="260" font-size="150" text-anchor="middle">${e}</text></svg>`;
  return 'data:image/svg+xml;utf8,' + encodeURIComponent(svg);
}

